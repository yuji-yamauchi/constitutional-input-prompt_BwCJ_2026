# 型 -> ((鍵, 画面の 字), ...)。鍵は 保存に 書く 字（英字）。画面の 字は 版で 変えない。
CHOICES = {
    "F": (("none", "なかった"), ("few", "1、2回"), ("sometimes", "ときどき"), ("often", "よく"), ("unsure", "わからない")),
    "E": (("yes", "あった"), ("no", "なかった"), ("unsure", "わからない")),
    "S": (("yes", "はい"), ("no", "いいえ"), ("unsure", "わからない")),
}

N_ITEMS = len(ITEMS)
_BY_ID = {row[0]: row for row in ITEMS}


def item(item_id):
    """id -> (id, 群, 型, 字)。無ければ None。"""
    return _BY_ID.get(item_id)


def choice_keys(item_id):
    """その 問いに 使える 選択肢の 鍵の 並び。無い id なら 空。"""
    row = _BY_ID.get(item_id)
    if row is None:
        return ()
    return tuple(k for k, _label in CHOICES[row[2]])


def pick_ids(start_id, count):
    """start_id から id の 順に count 個（60 を 超えたら 1 に 戻る）。"""
    if not isinstance(start_id, int) or start_id < 1 or start_id > N_ITEMS:
        start_id = 1
    out = []
    i = start_id
    while len(out) < min(count, N_ITEMS):
        out.append(i)
        i = 1 if i >= N_ITEMS else i + 1
    return out


def next_id_after(last_id):
    """前回 最後に 答えた id の つぎ（60 の つぎは 1）。前回が 無ければ 1。"""
    if not isinstance(last_id, int) or last_id < 1 or last_id >= N_ITEMS:
        return 1
    return last_id + 1


